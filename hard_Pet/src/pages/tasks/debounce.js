/*
Задача: реализовать функцию debounce.

Функция debounce принимает:
1. функцию fn
2. задержку delay в миллисекундах

Она должна вернуть новую функцию.

Если возвращённая функция вызывается несколько раз подряд,
каждый новый вызов должен отменять предыдущий таймер.

Исходная fn должна выполниться только один раз —
через delay миллисекунд после ПОСЛЕДНЕГО вызова.

Пример:

const log = debounce((value) => {
  console.log(value)
}, 500)

log('a')
log('b')
log('c')

Ожидаемый результат:

через 500 мс после последнего вызова:
c


Ещё пример:

const sum = debounce((a, b) => {
  console.log(a + b)
}, 300)

sum(2, 3)

Через 300 мс:
5


Условия:
- использовать setTimeout
- использовать clearTimeout
- использовать замыкание
- передавать аргументы в fn
- не использовать lodash
*/

function debounce(fn, delay) {
    let timer

    return (...args) => {
        if (timer) {
            clearTimeout(timer)
        }

        timer = setTimeout(() => {
            fn(...args)
        }, delay)
    }
}